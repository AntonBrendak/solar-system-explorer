import { mkdir, writeFile } from "node:fs/promises";

const output = new URL("../public/fonts/", import.meta.url);
await mkdir(output, { recursive: true });
const response = await fetch(
  "https://fonts.googleapis.com/css2?family=Inter:wght@400..700&family=Manrope:wght@400..700&display=swap",
  {
    headers: {
      "User-Agent":
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36",
    },
    signal: AbortSignal.timeout(20000),
  },
);
if (!response.ok) throw new Error(`Font CSS HTTP ${response.status}`);
const css = await response.text();
let count = 0;
const faces = [];
for (const match of css.matchAll(
  /\/\* (latin|cyrillic) \*\/\s*(@font-face \{[\s\S]*?\})/g,
)) {
  const family = /font-family: '([^']+)'/.exec(match[2])?.[1].toLowerCase();
  const url = /url\(([^)]+)\)/.exec(match[2])?.[1];
  if (!family || !url) continue;
  const font = await fetch(url, { signal: AbortSignal.timeout(20000) });
  if (!font.ok) throw new Error(`Font file HTTP ${font.status}`);
  await writeFile(
    new URL(`${family}-${match[1]}.woff2`, output),
    Buffer.from(await font.arrayBuffer()),
  );
  faces.push(
    match[2].replace(
      /url\([^)]+\)/,
      `url('/fonts/${family}-${match[1]}.woff2')`,
    ),
  );
  count++;
}
if (count !== 4) throw new Error(`Expected 4 font subsets, received ${count}`);
await writeFile(
  new URL("../../shared/styles/fonts.css", output),
  `/* Generated by scripts/prepare-fonts.mjs; preserve the source Unicode ranges. */\n${faces.join("\n\n")}\n`,
);
for (const family of ["inter", "manrope"]) {
  const license = await fetch(
    `https://raw.githubusercontent.com/google/fonts/main/ofl/${family}/OFL.txt`,
    { signal: AbortSignal.timeout(20000) },
  );
  if (!license.ok) throw new Error(`Font license HTTP ${license.status}`);
  await writeFile(new URL(`${family}-OFL.txt`, output), (await license.text()).replace(/[ \t]+$/gm, ""));
}
console.log("Prepared Inter and Manrope, Latin/Cyrillic, with OFL licenses.");
